      <h3>翻译上的三处说明</h3>
      <ul>
        <li>
          <strong>第 3 题的 <code>speeded up</code></strong>
          指精神运动性加速——思维变快、活动变多、整个人像被按了快进键，是双相谱系的核心描述之一，不能译作「觉得时间过得很快」。流传版正是把它误译成了后者。
        </li>
        <li>
          <strong>六级选项</strong>原文是对<em>程度</em>的评定（Not at all … Very
          much），本站译为「完全没有／稍微有一点／有一些／中等程度／相当明显／非常明显」。流传版译作「完全不符合或几乎不符合／稍微符合／有点符合／比较符合／较多符合／非常符合或完全符合」，把程度评定改成了符合度评定；虽同为六级
          0~5 计分，语义已略有偏移。
        </li>
        <li>
          <strong>指导语的时间框架</strong
          >为「你一生大部分时间里的感受与行为」，且明确「如果你一贯是某种样子、只是近期发生了变化，应当按你一贯的样子作答」。流传版常见的「根据你最近一个星期的实际感觉」把时间框架整个改错，会直接影响作答。
        </li>
      </ul>
