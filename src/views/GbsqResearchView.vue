    <h2>六、讹传是如何产生的</h2>
    <div class="content-box">
      <ol>
        <li>
          <strong>原版没有缩写。</strong>「Goldberg Bipolar Screening
          Quiz」不是量表代号，国内站点需要短码做 URL
          与标签，于是就地造出「BSQ」，再倒推出一个并不存在的英文全称。百度健康「bsq 全称 bipolar
          spectrum questionnaire」的写法把这个倒推过程暴露得很清楚。
        </li>
        <li>
          <strong>作者信息在转载链中丢失。</strong
          >原版只有网页上的一行版权声明，没有论文、没有单位、没有手册，抄录时最容易丢的就是作者栏。后续内容农场（其中不少读起来是
          SEO 生成的科普文）便用双相筛查领域最知名的名字 Hirschfeld 去填空。
        </li>
        <li>
          <strong>与 MDQ 彻底混同。</strong>Hirschfeld 名下真正的双相筛查工具是
          <router-link to="/scale/mdq">心境障碍问卷（MDQ）</router-link>
          ——13 项是／否、划界分
          7。讹传页面把这些参数直接套到了「BSQ」上：道客巴巴《测试双相障碍的量表》写「双相情感障碍自评量表(BSQ)
          自评量表由美国精神病学家 Hirschfeld 等编制，共 13
          个条目……受试者只需回答『是』或『否』……划界分为 7 分」；吉林中山精神心理写「主要包含 12
          个关于双相障碍症状的是/非问题」却配 0~3 级评分，自相矛盾。
        </li>
        <li>
          <strong>中文题目被改动后无法反查。</strong
          >删掉原版的性兴趣条目、换成一条原版没有的食欲条目，再把
          <code>speeded up</code>
          误译成「时间过得很快」，中文文本已经搜不回英文原版，纠错路径被切断。
        </li>
        <li>
          <strong>正确来源被淹没。</strong
          >壹心理／才储／寸辛归属正确，但它们不带「BSQ」这个标签，在搜索结果里被大量带 BSQ 的 SEO
          页面压住。
        </li>
        <li>
          <strong>原址下线。</strong>Psych Central 现役页面已改写成通用的「Bipolar Disorder
          Test」，Goldberg 版只能从互联网档案馆取得，后来者几乎不可能查到出处。
        </li>
      </ol>
